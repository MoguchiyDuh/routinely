CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL,
    password_hash TEXT NOT NULL,
    timezone TEXT NOT NULL DEFAULT 'UTC',
    created_at TEXT NOT NULL,
    last_evaluated_day TEXT,
    avatar_path TEXT,
    avatar_icon TEXT,
    avatar_color BIGINT,
    onboarding_dismissed_at TEXT
);

CREATE UNIQUE INDEX idx_users_username ON users (lower(username));

CREATE TABLE routines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    title TEXT NOT NULL,
    notes TEXT,
    kind TEXT NOT NULL CHECK (kind IN ('weekdays','count')),
    weekdays_mask BIGINT CHECK (weekdays_mask IS NULL OR (weekdays_mask BETWEEN 1 AND 127)),
    period TEXT CHECK (period IS NULL OR period IN ('day','week','month','year')),
    per_period BIGINT CHECK (per_period IS NULL OR per_period > 0),
    iterations BIGINT CHECK (iterations IS NULL OR iterations > 0),
    start_date TEXT NOT NULL,
    end_date TEXT,
    time_of_day TEXT,
    time_end TEXT,
    created_at TEXT NOT NULL,
    archived_at TEXT,
    previous_id BIGINT REFERENCES routines(id)
);

CREATE INDEX idx_routines_user ON routines(user_id);
CREATE INDEX idx_routines_previous ON routines(previous_id);

CREATE TABLE occurrences (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    routine_id BIGINT NOT NULL REFERENCES routines(id) ON DELETE CASCADE,
    due_date TEXT NOT NULL,
    period_start TEXT,
    created_at TEXT NOT NULL,
    UNIQUE (routine_id, due_date)
);

CREATE INDEX idx_occurrences_due ON occurrences(due_date);

CREATE TABLE completions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurrence_id BIGINT NOT NULL UNIQUE REFERENCES occurrences(id) ON DELETE CASCADE,
    completed_at TEXT NOT NULL,
    evidence_note TEXT
);

CREATE TABLE pins (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    completion_id BIGINT NOT NULL UNIQUE REFERENCES completions(id) ON DELETE CASCADE,
    summary TEXT NOT NULL,
    created_at TEXT NOT NULL
);

CREATE TABLE attachments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pin_id BIGINT NOT NULL REFERENCES pins(id) ON DELETE CASCADE,
    kind TEXT NOT NULL CHECK (kind IN ('link','photo')),
    url TEXT,
    file_path TEXT,
    created_at TEXT NOT NULL,
    CHECK (kind = 'link' AND url IS NOT NULL OR kind = 'photo' AND file_path IS NOT NULL)
);

CREATE INDEX idx_attachments_pin ON attachments(pin_id);

CREATE TABLE punishment_catalog (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    description TEXT,
    active BIGINT NOT NULL DEFAULT 1 CHECK (active IN (0,1)),
    created_by BIGINT NOT NULL REFERENCES users(id),
    created_at TEXT NOT NULL
);

CREATE TABLE punishments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    catalog_id BIGINT REFERENCES punishment_catalog(id) ON DELETE SET NULL,
    custom_title TEXT,
    source TEXT NOT NULL CHECK (source IN ('auto','manual')),
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','cleared','waived')),
    occurrence_id BIGINT REFERENCES occurrences(id) ON DELETE SET NULL,
    assigned_at TEXT NOT NULL,
    cleared_at TEXT,
    miss_day TEXT,
    routine_id BIGINT REFERENCES routines(id) ON DELETE SET NULL,
    period_start TEXT
);

CREATE UNIQUE INDEX idx_punishments_occurrence ON punishments(occurrence_id) WHERE occurrence_id IS NOT NULL;
CREATE INDEX idx_punishments_miss_day ON punishments(user_id, miss_day) WHERE source = 'auto';

CREATE TABLE period_misses (
    routine_id BIGINT NOT NULL REFERENCES routines(id) ON DELETE CASCADE,
    period_start TEXT NOT NULL,
    created_at TEXT NOT NULL,
    PRIMARY KEY (routine_id, period_start)
);

CREATE TABLE todos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    title TEXT NOT NULL,
    notes TEXT,
    deadline TEXT,
    completed_at TEXT,
    created_at TEXT NOT NULL,
    kind TEXT NOT NULL DEFAULT 'todo' CHECK (kind IN ('todo','deadline')),
    all_day BIGINT NOT NULL DEFAULT 0 CHECK (all_day IN (0,1))
);

CREATE INDEX idx_todos_user ON todos(user_id);

CREATE TABLE daily_notes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    day TEXT NOT NULL,
    body TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    UNIQUE (user_id, day)
);
